#!/usr/bin/env node
/**
 * Build-time SEO data generator for /resume-examples/[role]/.
 *
 * Fetches per-role aggregates from the resunova-api jobs dataset and rewrites
 * the data array inside lib/roleResumeData.ts (between the <generated:role-data>
 * markers). Run BEFORE `next build` so the static export bakes fresh data in.
 *
 *   node scripts/build-seo-data.mjs
 *   SEO_DATA_API_BASE=https://api.resunova.io node scripts/build-seo-data.mjs
 *
 * SAFE BY DESIGN: if the endpoint is missing/unreachable/returns nothing usable,
 * the script logs a warning and exits 0 WITHOUT touching the committed snapshot,
 * so wiring it into CI today cannot break the build before the endpoint ships.
 *
 * Expected response from GET /api/seo/role-stats — an array of objects matching
 * the RoleResumeData shape in lib/roleResumeData.ts:
 *   { slug, label, roleFamily, postingsAnalyzed, intro,
 *     topSkills: [{ name, sharePct }], salary: { medianUsd, rangeLabel },
 *     workModel: { remotePct, hybridPct, onsitePct },
 *     example: { summary, bullets: [...], score }, faq: [{ question, answer }] }
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DATA_FILE = join(__dirname, "..", "lib", "roleResumeData.ts");

const API_BASE = (
  process.env.SEO_DATA_API_BASE ||
  process.env.NEXT_PUBLIC_API_URL ||
  "https://api.resunova.io"
).replace(/\/$/, "");
const ENDPOINT = `${API_BASE}/api/seo/role-stats`;

const START = "// <generated:role-data>";
const END = "// </generated:role-data>";

function warnAndKeep(msg) {
  console.warn(`[build-seo-data] ${msg}`);
  console.warn("[build-seo-data] Keeping committed snapshot in lib/roleResumeData.ts (no changes).");
  process.exit(0);
}

/** Minimal validation so we never write garbage over good seed data. */
function isUsable(roles) {
  return (
    Array.isArray(roles) &&
    roles.length > 0 &&
    roles.every(
      (r) =>
        r &&
        typeof r.slug === "string" &&
        typeof r.label === "string" &&
        Array.isArray(r.topSkills) &&
        r.topSkills.length > 0 &&
        r.example &&
        Array.isArray(r.example.bullets),
    )
  );
}

async function main() {
  let roles;
  try {
    const res = await fetch(ENDPOINT, { headers: { accept: "application/json" } });
    if (!res.ok) warnAndKeep(`GET ${ENDPOINT} → HTTP ${res.status}.`);
    const body = await res.json();
    roles = Array.isArray(body) ? body : body?.roles;
  } catch (err) {
    warnAndKeep(`Could not reach ${ENDPOINT}: ${err?.message ?? err}.`);
  }

  if (!isUsable(roles)) warnAndKeep("Endpoint returned no usable role data.");

  const today = new Date().toISOString().slice(0, 10);
  const literal =
    `${START} — generated by scripts/build-seo-data.mjs on ${today}. Do not edit by hand.\n` +
    `export const SAMPLE_ROLE_RESUME_DATA: RoleResumeData[] = ${JSON.stringify(roles, null, 2)};\n` +
    END;

  const src = readFileSync(DATA_FILE, "utf8");
  const startIdx = src.indexOf(START);
  const endIdx = src.indexOf(END);
  if (startIdx === -1 || endIdx === -1) {
    warnAndKeep(`Markers ${START} / ${END} not found in lib/roleResumeData.ts.`);
  }

  let next = src.slice(0, startIdx) + literal + src.slice(endIdx + END.length);
  // Refresh the snapshot date stamp.
  next = next.replace(
    /export const ROLE_DATA_LAST_UPDATED = "[^"]*";/,
    `export const ROLE_DATA_LAST_UPDATED = "${today}";`,
  );

  writeFileSync(DATA_FILE, next, "utf8");
  console.log(`[build-seo-data] Wrote ${roles.length} roles to lib/roleResumeData.ts (updated ${today}).`);
}

main();
